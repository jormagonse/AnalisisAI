def normalize_text(s: str) -> str:
    if not s:
        return ""
    s = s.upper()
    s = unicodedata.normalize("NFD", s)
    s = "".join(c for c in s if unicodedata.category(c) != "Mn")
    s = re.sub(r"\s+", " ", s).strip()
    return s

def extraer_meta_desde_path(path_pdf: str):
    """
    path_pdf: /content/drive/.../AIs/full/nomjuzgado/mes/archivo.pdf
    Devuelve nomjuzgado_dir, mes_dir.
    """
    rel = os.path.relpath(path_pdf, CARPETA_FULL)
    parts = rel.split(os.sep)
    nomjuzgado = parts[0] if len(parts) >= 3 else ""
    mes_dir = parts[1] if len(parts) >= 3 else ""
    return {
        "nomjuzgado_dir": nomjuzgado,
        "mes_dir": mes_dir
    }

def extraer_meta_desde_nombre(nombre_pdf: str):
    """
    Ejemplo: Auto_Interlocutorio_Nro_3_2025_F_03-01-2025.pdf
    """
    base = os.path.basename(nombre_pdf)
    tipo_resolucion = "n/a"
    nro_ai = "n/a"
    anio_ai = "n/a"
    fecha_norm = "n/a"

    # Tipo resolución básico
    if base.startswith("Auto_Interlocutorio"):
        tipo_resolucion = "Auto Interlocutorio"

    # Nro, año y fecha
    m = re.search(r"Nro_([0-9]+)_([0-9]{4})_F_([0-9]{2})-([0-9]{2})-([0-9]{4})\.pdf$", base)
    if m:
        nro_ai = m.group(1)
        anio_ai = m.group(2)
        d, mth, y = m.group(3), m.group(4), m.group(5)
        try:
            dt = datetime.strptime(f"{d}-{mth}-{y}", "%d-%m-%Y")
            fecha_norm = dt.strftime("%d/%m/%Y")
        except ValueError:
            fecha_norm = f"{d}/{mth}/{y}"

    return {
        "tipo_resolucion_archivo": tipo_resolucion,
        "numero_ai_archivo": nro_ai,
        "anio_ai_archivo": anio_ai,
        "fecha_resolucion_archivo": fecha_norm
    }

