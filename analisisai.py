def intentar_reparar_json(texto_bruto: str):
    """
    Intenta parsear el JSON. Si falla, aplica heurísticas:
    - eliminar basura antes de la primera '{',
    - recortar hasta última '}' válida,
    - eliminar comas colgantes antes de ']' o '}',
    - rebalancear llaves y corchetes.
    Devuelve dict/list o None.
    """
    if not isinstance(texto_bruto, str):
        return None

    # Intento directo
    try:
        return json.loads(texto_bruto)
    except json.JSONDecodeError:
        pass

    s = texto_bruto.strip()

    # Quitar basura antes de la primera llave
    primera = s.find("{")
    if primera > 0:
        s = s[primera:]

    # Recortar hasta la última llave de cierre
    ultima = s.rfind("}")
    if ultima != -1:
        s = s[:ultima+1]

    # Eliminar comas colgantes antes de ']' o '}'
    s = re.sub(r",(\s*[\]\}])", r"\1", s)

    # Balancear llaves
    n_open = s.count("{")
    n_close = s.count("}")
    if n_open > n_close:
        s += "}" * (n_open - n_close)

    # Balancear corchetes
    b_open = s.count("[")
    b_close = s.count("]")
    if b_open > b_close:
        s += "]" * (b_open - b_close)

    # Reintento final
    try:
        return json.loads(s)
    except json.JSONDecodeError:
        return None


